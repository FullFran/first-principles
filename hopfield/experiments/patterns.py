"""The patterns to store, written out so you can read them.

The class version used photographs (a cat, Batman, a self-portrait). Those
cannot live in a public repo, and photographs are also heavily biased towards
one colour, which correlates the patterns and quietly wrecks Hebbian recall.

The first replacement was abstract -- a ring, a cross, diagonal bars. Balanced
and reproducible, and unrecognisable: a 24x24 ring says nothing to a reader,
so a figure showing one recovered from noise demonstrates nothing anybody can
check by eye. Recall is only convincing if you can see what was recalled.

These are letters, and choosing them took measuring rather than taste. Letters
sit on a shared background, so they are correlated by construction: `FRAN` and
`AENX` both recall 0 of 4 patterns from 25% noise, and the least correlated
four-letter set in the alphabet manages 2. `MATH` recalls 4 of 4 at every noise
level up to 35%, across six seeds. Most sets do not work; this one had to be
found.

They are stored as literal art rather than rendered from a font. A font is a
dependency that can be absent, substituted or reflowed between versions, and
the point of an entry here is that it still works once you copy the folder
out. It also makes the patterns legible in the source, which is the one place
in this repo where the data is part of the argument.
"""

