NAMES = ("M", "A", "T", "H")
NEAR_MISS = "N"          # overlaps the stored H at +0.875 -- a letter, not a memory


def _mask(art):
    rows = [line for line in art.strip("\n").split("\n") if line]
    if len(rows) != SIDE or any(len(row) != SIDE for row in rows):
        raise ValueError(f"a glyph must be {SIDE}x{SIDE}, got {len(rows)} rows of "
                         f"{sorted({len(r) for r in rows})}")
    return np.array([[character == "#" for character in row] for row in rows])


def glyph(name):
    if name not in GLYPHS:
        raise ValueError(f"unknown glyph {name!r}; available: {sorted(GLYPHS)}")
    return _mask(GLYPHS[name])


def checker(period=6):
    """Not a letter at all, and the only genuinely unrelated probe available.

    Every glyph here overlaps every other by at least 0.67 simply by sharing a
    background, so no letter can play the part of "unrelated". A balanced
    checkerboard can.
    """
    rows, columns = np.meshgrid(np.arange(SIDE), np.arange(SIDE), indexing="ij")
    return ((rows // period) + (columns // period)) % 2 == 0


def as_pattern(mask):
    return np.where(mask, 1, -1).astype(np.int8).ravel()


def library(names=NAMES):
    return np.stack([as_pattern(glyph(name)) for name in names])


def render(state):
    grid = np.asarray(state).reshape(SHAPE)
    return "\n".join("".join("#" if value > 0 else "." for value in row)
                     for row in grid)
